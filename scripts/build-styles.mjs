#!/usr/bin/env node
/**
 * Assemble the shipped stylesheet.
 *
 * `styles.css` is the base layer plus the shared component styles, in that
 * order. Tokens are a separate import so a consumer can take the values
 * without the opinions — `internal` may want the palette applied to its own
 * chrome without inheriting Ekdotico's table and callout treatments.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ROOT, 'dist', 'styles');
mkdirSync(OUT, { recursive: true });

const parts = ['base.css', 'primitives.css', 'components.css'].map((f) =>
  readFileSync(join(ROOT, 'src', 'styles', f), 'utf8').trim(),
);

const header = `/**
 * @ekdotico/design-system — base layer and shared components.
 *
 * Import AFTER the tokens, which define every custom property used here:
 *
 *   import '@ekdotico/design-system/tokens.css';
 *   import '@ekdotico/design-system/styles.css';
 *
 * Assembled from src/styles/. Do not edit this file.
 */
`;

writeFileSync(join(OUT, 'base.css'), `${header}\n${parts.join('\n\n')}\n`);

const lines = parts.join('\n').split('\n').length;
console.log(`dist/styles/base.css — ${lines} lines (base layer + shared components)`);
